let bag: string[] = [];
let previous = '';

export function nextSandPhrase() {
  if (!bag.length) {
    bag = [...SAND_PHRASES];

    for (let i = bag.length - 1; i > 0; i -= 1) {
      const j = randomIndex(i + 1);

      [bag[i], bag[j]] = [bag[j], bag[i]];
    }

    if (bag.at(-1) === previous) {
      [bag[0], bag[bag.length - 1]] = [bag[bag.length - 1], bag[0]];
    }
  }

  previous = bag.pop() as string;

  return previous;
}
